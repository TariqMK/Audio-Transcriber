"""Builds every Verbatica brand image from the icon masters in assets/icon/.

Writes:
  assets/icon/verbatica.png    1024 x 1024 px (Linux, docs)
  assets/icon/verbatica.ico    16-256 px, PNG-encoded (Windows build)
  assets/icon/verbatica.icns   16-1024 px including @2x sizes (macOS build)
  verbatica/_icon.py           the window icon, embedded in the app as PNG data
  assets/banner.png            README banner, 1280 x 320 px drawn at 2x (2560 x 640)
  assets/social-card.png       GitHub social preview, 1280 x 640 px, GitHub's repo-card layout

Sizes of 32 px and below use verbatica-small.svg; larger sizes use verbatica.svg.
Colours come from the app's dark theme (verbatica/app.py). Change NAME or TAGLINE here only.

Run from the project root:
  pip install PyQt6 pillow
  python assets/make_assets.py
  python assets/make_assets.py --guides <file.png>   (also writes the card with its safe area drawn)
"""

from __future__ import annotations

import base64
import io
import os
import sys
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PIL import Image  # noqa: E402
from PyQt6.QtCore import QBuffer, QIODevice, QPointF, QRectF, Qt  # noqa: E402
from PyQt6.QtGui import (QColor, QFont, QFontDatabase, QFontMetrics, QGuiApplication,  # noqa: E402
                         QImage, QPainter, QPen)
from PyQt6.QtSvg import QSvgRenderer  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "assets" / "icon"
MASTER = ICON_DIR / "verbatica.svg"
SMALL = ICON_DIR / "verbatica-small.svg"
SMALL_MAX = 32  # sizes up to this use the simplified master

ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]
ICNS_SIZES = [16, 32, 64, 128, 256, 512, 1024]
# .icns slot type and its size in px: 16, 32, 128, 256, 512 pt at 1x and @2x.
ICNS_TYPES = [(b"icp4", 16), (b"ic11", 32), (b"icp5", 32), (b"ic12", 64), (b"ic07", 128),
              (b"ic13", 256), (b"ic08", 256), (b"ic14", 512), (b"ic09", 512), (b"ic10", 1024)]
WINDOW_SIZES = [16, 32, 64, 256]

NAME = "Verbatica"
TAGLINE = "Speech to text, on your computer."
SUBLINE = "Windows · macOS · Linux"

# The app's dark theme: Base (darkest background), text, version-button grey, border.
BACKGROUND = "#232323"
BORDER = "#3a3a3a"
PRIMARY = "#f2f2f2"
SECONDARY = "#a6a6a6"
MUTED = "#8c8c8c"
SANS = ["Segoe UI", "Inter", "SF Pro Display", "Helvetica Neue", "Arial"]
MONO = ["Cascadia Mono", "Consolas", "SF Mono", "Menlo", "DejaVu Sans Mono"]
TILE = QRectF(96, 96, 832, 832)  # the icon's visible tile inside its 1024 viewBox (with border)


def render(size: int) -> Image.Image:
    """Renders the right master at `size` px and returns it as a Pillow RGBA image."""
    svg = SMALL if size <= SMALL_MAX else MASTER
    img = QImage(size, size, QImage.Format.Format_ARGB32)
    img.fill(Qt.GlobalColor.transparent)
    painter = QPainter(img)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(str(svg)).render(painter, QRectF(0, 0, size, size))
    painter.end()
    buffer = QBuffer()
    buffer.open(QIODevice.OpenModeFlag.WriteOnly)
    img.save(buffer, "PNG")
    return Image.open(io.BytesIO(bytes(buffer.data()))).convert("RGBA")


def png_bytes(image: Image.Image) -> bytes:
    out = io.BytesIO()
    image.save(out, "PNG", optimize=True)
    return out.getvalue()


def write_icns(path: Path, renders: dict[int, Image.Image]) -> None:
    """Writes a macOS .icns with every 1x and @2x slot from 16 to 512 pt, each as PNG data.
    Pillow's writer leaves out the 16 and 32 px 1x slots, so the file is built here."""
    chunks = b""
    for code, size in ICNS_TYPES:
        data = png_bytes(renders[size])
        chunks += code + (8 + len(data)).to_bytes(4, "big") + data
    path.write_bytes(b"icns" + (8 + len(chunks)).to_bytes(4, "big") + chunks)


def make_icons() -> None:
    renders = {size: render(size) for size in sorted(set(ICO_SIZES + ICNS_SIZES + WINDOW_SIZES))}
    big = renders[1024]
    big.save(ICON_DIR / "verbatica.png", optimize=True)

    ico_frames = [renders[s] for s in ICO_SIZES]
    ico_frames[-1].save(ICON_DIR / "verbatica.ico", sizes=[(s, s) for s in ICO_SIZES],
                        append_images=ico_frames[:-1])

    write_icns(ICON_DIR / "verbatica.icns", renders)

    lines = ['"""Generated by assets/make_assets.py. Do not edit. The window icon as PNG data."""', "",
             "ICON_PNGS = {"]
    for size in WINDOW_SIZES:
        data = base64.b64encode(png_bytes(renders[size])).decode()
        lines.append(f'    {size}: "{data}",')
    lines += ["}", ""]
    (ROOT / "verbatica" / "_icon.py").write_text("\n".join(lines))


def font(families: list[str], pixel_size: int, weight: QFont.Weight) -> QFont:
    available = set(QFontDatabase.families())
    result = QFont()
    result.setFamilies([f for f in families if f in available] or families)
    result.setPixelSize(pixel_size)
    result.setWeight(weight)
    return result


def fit(base: QFont, text: str, max_width: float) -> QFont:
    """Shrinks the font 2 px at a time until the text fits max_width."""
    result = QFont(base)
    while QFontMetrics(result).horizontalAdvance(text) > max_width - 8 and result.pixelSize() > 12:
        result.setPixelSize(result.pixelSize() - 2)
    if result.pixelSize() < base.pixelSize():
        print(f'Warning: "{text}" shrank to {result.pixelSize()} px to fit. A shorter text looks better.')
    return result


def draw_tile(painter: QPainter, rect: QRectF) -> None:
    """Draws the icon cropped to its tile, so its size matches the layout values exactly."""
    renderer = QSvgRenderer(str(MASTER))
    renderer.setViewBox(TILE)
    renderer.render(painter, rect)


def new_canvas(width: int, height: int, fill) -> tuple[QImage, QPainter]:
    image = QImage(width, height, QImage.Format.Format_ARGB32)
    image.fill(fill)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.TextAntialiasing)
    return image, painter


def make_banner() -> Path:
    """1280 x 320 px at 2x: rounded panel, icon left, name and tagline right, centred as one group."""
    width, height, scale = 1280, 320, 2
    icon_px, gap, line_gap = 176, 40, 22
    image, painter = new_canvas(width * scale, height * scale, Qt.GlobalColor.transparent)
    painter.scale(scale, scale)
    painter.setPen(QPen(QColor(BORDER), 1))
    painter.setBrush(QColor(BACKGROUND))
    painter.drawRoundedRect(QRectF(0.5, 0.5, width - 1, height - 1), 24, 24)

    name_font = font(SANS, 96, QFont.Weight.DemiBold)
    tag_font = font(MONO, 24, QFont.Weight.Normal)
    name_m, tag_m = QFontMetrics(name_font), QFontMetrics(tag_font)
    text_width = max(name_m.horizontalAdvance(NAME), tag_m.horizontalAdvance(TAGLINE))
    left = (width - (icon_px + gap + text_width)) / 2
    draw_tile(painter, QRectF(left, (height - icon_px) / 2, icon_px, icon_px))

    # Name cap height plus tagline x-height block, centred on the icon's centre line.
    block = name_m.capHeight() + line_gap + tag_m.capHeight()
    name_base = (height - block) / 2 + name_m.capHeight()
    tag_base = name_base + line_gap + tag_m.capHeight()
    x = left + icon_px + gap
    painter.setFont(name_font)
    painter.setPen(QColor(PRIMARY))
    painter.drawText(QPointF(x - name_font.pixelSize() * 0.035, name_base), NAME)
    painter.setFont(tag_font)
    painter.setPen(QColor(SECONDARY))
    painter.drawText(QPointF(x, tag_base), TAGLINE)
    painter.end()
    out = ROOT / "assets" / "banner.png"
    image.save(str(out))
    return out


# Social card: fixed repo-card layout (same values as the make_social_card.py template).
CARD_W, CARD_H, SAFE = 1280, 640, 80
CARD_ICON, CARD_ICON_TOP, CARD_ICON_GAP = 168, 150, 40
CARD_NAME_PX, CARD_NAME_SPACING = 112, 98
CARD_TAGLINE_PX, CARD_TAGLINE_BASELINE = 34, 420
CARD_SUBLINE_PX, CARD_SUBLINE_BASELINE = 24, 476


def make_social_card(guides: Path | None = None) -> Path:
    image, painter = new_canvas(CARD_W, CARD_H, QColor(BACKGROUND))  # full bleed
    safe_width = CARD_W - 2 * SAFE
    name_font = font(SANS, CARD_NAME_PX, QFont.Weight.DemiBold)
    name_font.setLetterSpacing(QFont.SpacingType.PercentageSpacing, CARD_NAME_SPACING)
    icon_part = CARD_ICON + CARD_ICON_GAP
    name_font = fit(name_font, NAME, safe_width - icon_part)
    name_width = QFontMetrics(name_font).horizontalAdvance(NAME)
    left = (CARD_W - (icon_part + name_width)) / 2
    draw_tile(painter, QRectF(left, CARD_ICON_TOP, CARD_ICON, CARD_ICON))
    baseline = CARD_ICON_TOP + CARD_ICON / 2 + QFontMetrics(name_font).capHeight() / 2
    painter.setFont(name_font)
    painter.setPen(QColor(PRIMARY))
    painter.drawText(QPointF(left + icon_part - name_font.pixelSize() * 0.035, baseline), NAME)

    for text, px, color, y in [(TAGLINE, CARD_TAGLINE_PX, SECONDARY, CARD_TAGLINE_BASELINE),
                               (SUBLINE, CARD_SUBLINE_PX, MUTED, CARD_SUBLINE_BASELINE)]:
        text_font = fit(font(MONO, px, QFont.Weight.Normal), text, safe_width)
        painter.setFont(text_font)
        painter.setPen(QColor(color))
        painter.drawText(QPointF((CARD_W - QFontMetrics(text_font).horizontalAdvance(text)) / 2, y), text)
    painter.end()

    out = ROOT / "assets" / "social-card.png"
    image.save(str(out))
    check_safe_area(image)
    if guides:
        copy = image.copy()
        p = QPainter(copy)
        p.setPen(QPen(QColor("#d1242f"), 2))
        p.drawRect(SAFE, SAFE, CARD_W - 2 * SAFE, CARD_H - 2 * SAFE)
        p.end()
        copy.save(str(guides))
    return out


def check_safe_area(image: QImage) -> None:
    """Stops with an error if anything is drawn within 80 px of an edge."""
    bg = QColor(BACKGROUND)
    xs, ys = [], []
    for y in range(0, image.height()):
        for x in range(0, image.width()):
            if image.pixelColor(x, y) != bg:
                xs.append(x)
                ys.append(y)
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
    print(f"Social card content: x {x0}-{x1}, y {y0}-{y1}; safe area x {SAFE}-{CARD_W - SAFE}, "
          f"y {SAFE}-{CARD_H - SAFE}")
    if x0 < SAFE or y0 < SAFE or x1 > CARD_W - SAFE or y1 > CARD_H - SAFE:
        sys.exit("Social card content is outside the safe area")


def main() -> int:
    app = QGuiApplication(sys.argv[:1])  # noqa: F841 (Qt needs an application object to paint)
    guides = Path(sys.argv[sys.argv.index("--guides") + 1]) if "--guides" in sys.argv else None
    make_icons()
    for name in ["verbatica.png", "verbatica.ico", "verbatica.icns"]:
        print(ICON_DIR / name)
    print(ROOT / "verbatica" / "_icon.py")
    print(make_banner())
    print(make_social_card(guides))
    return 0


if __name__ == "__main__":
    sys.exit(main())
